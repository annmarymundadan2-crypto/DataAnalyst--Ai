# ==========================================
# AI DATA ANALYST MODEL
# Python + Pandas + NumPy + spaCy
# ==========================================

import pandas as pd
import numpy as np
import spacy
import os

# Load NLP model
nlp = spacy.load("en_core_web_sm")

# ==========================================
# STEP 1: LOAD DATASET
# ==========================================

file_path = input("Enter your dataset file path: ")

def load_dataset(file_path):

    extension = os.path.splitext(file_path)[1].lower()

    if extension == ".csv":
        data = pd.read_csv(file_path)

    elif extension in [".xlsx", ".xls"]:
        data = pd.read_excel(file_path)

    elif extension == ".json":
        data = pd.read_json(file_path)

    elif extension == ".txt":
        data = pd.read_csv(file_path, sep=None, engine="python")

    else:
        raise ValueError("Unsupported file format")

    return data


df = load_dataset(file_path)

print("\nDataset Loaded Successfully!")
print(df.head())

# ==========================================
# STEP 2: DATASET INFORMATION
# ==========================================

print("\n========== DATASET INFORMATION ==========")

print("Rows:", df.shape[0])
print("Columns:", df.shape[1])

print("\nColumn Names:")
print(df.columns.tolist())

print("\nData Types:")
print(df.dtypes)

# ==========================================
# STEP 3: IDENTIFY MISSING VALUES
# ==========================================

print("\n========== MISSING VALUES ==========")

missing_values = df.isnull().sum()

print(missing_values)

# ==========================================
# STEP 4: REMOVE DUPLICATES
# ==========================================

duplicate_count = df.duplicated().sum()

print("\nDuplicate Records:", duplicate_count)

df = df.drop_duplicates()

print("Duplicates Removed Successfully!")

# ==========================================
# STEP 5: REMOVE EMPTY COLUMNS
# ==========================================

df = df.dropna(axis=1, how="all")

print("\nEmpty Columns Removed!")

# ==========================================
# STEP 6: AUTOMATIC DATA TYPE DETECTION
# ==========================================

for column in df.columns:

    # Convert text columns to numerical
    if df[column].dtype == "object":

        numeric_data = pd.to_numeric(
            df[column],
            errors="coerce"
        )

        valid_values = numeric_data.notna().sum()

        if valid_values > 0:

            percentage = valid_values / len(df)

            if percentage >= 0.80:
                df[column] = numeric_data

    # Detect date columns
    if df[column].dtype == "object":

        date_data = pd.to_datetime(
            df[column],
            errors="coerce"
        )

        valid_dates = date_data.notna().sum()

        if valid_dates > 0:

            percentage = valid_dates / len(df)

            if percentage >= 0.80:
                df[column] = date_data


print("\nData Types Corrected!")
print(df.dtypes)

# ==========================================
# STEP 7: FILL MISSING VALUES
# ==========================================

for column in df.columns:

    if df[column].isnull().sum() > 0:

        # Numerical columns
        if pd.api.types.is_numeric_dtype(df[column]):

            median_value = df[column].median()

            df[column] = df[column].fillna(median_value)

        # Text columns
        else:

            mode_value = df[column].mode()

            if len(mode_value) > 0:

                df[column] = df[column].fillna(
                    mode_value[0]
                )

            else:

                df[column] = df[column].fillna("Unknown")


print("\nMissing Values Filled Successfully!")

# ==========================================
# STEP 8: OUTLIER DETECTION
# ==========================================

outlier_report = {}

for column in df.select_dtypes(include=np.number).columns:

    Q1 = df[column].quantile(0.25)

    Q3 = df[column].quantile(0.75)

    IQR = Q3 - Q1

    lower_limit = Q1 - 1.5 * IQR

    upper_limit = Q3 + 1.5 * IQR

    outliers = df[
        (df[column] < lower_limit) |
        (df[column] > upper_limit)
    ]

    outlier_report[column] = len(outliers)

    # Cap extreme values
    df[column] = df[column].clip(
        lower=lower_limit,
        upper=upper_limit
    )


print("\n========== OUTLIER REPORT ==========")

for column, count in outlier_report.items():

    print(column, ":", count, "Outliers")

# ==========================================
# STEP 9: BASIC DATA ANALYSIS
# ==========================================

print("\n========== STATISTICAL ANALYSIS ==========")

print(df.describe())


# ==========================================
# STEP 10: CORRELATION ANALYSIS
# ==========================================

numerical_columns = df.select_dtypes(
    include=np.number
)

if len(numerical_columns.columns) > 1:

    correlation = numerical_columns.corr()

    print("\n========== CORRELATION ==========")

    print(correlation)

# ==========================================
# STEP 11: CATEGORICAL DATA ANALYSIS
# ==========================================

print("\n========== CATEGORY ANALYSIS ==========")

categorical_columns = df.select_dtypes(
    include=["object", "category"]
)

for column in categorical_columns.columns:

    print("\nColumn:", column)

    print(df[column].value_counts().head(5))

# ==========================================
# STEP 12: NLP ANALYSIS USING SPACY
# ==========================================

print("\n========== NLP ANALYSIS ==========")

text_data = ""

for column in df.select_dtypes(
    include=["object", "category"]
).columns:

    text_data += " ".join(
        df[column].astype(str).tolist()
    )


doc = nlp(text_data)

# Extract important words
important_words = []

for token in doc:

    if (
        token.is_alpha
        and not token.is_stop
        and token.pos_ in ["NOUN", "PROPN"]
    ):

        important_words.append(token.lemma_.lower())


word_frequency = pd.Series(
    important_words
).value_counts().head(10)


print("\nImportant Words:")

print(word_frequency)

# ==========================================
# STEP 13: GENERATE AI INSIGHTS
# ==========================================

print("\n========== AI DATA INSIGHTS ==========")

print("Total Records:", len(df))

print("Total Columns:", len(df.columns))

print("Duplicate Records Removed:", duplicate_count)

print("Missing Values Filled:", missing_values.sum())


# Numerical Insights
for column in df.select_dtypes(
    include=np.number
).columns:

    print("\nAnalysis of:", column)

    print("Average:", round(df[column].mean(), 2))

    print("Maximum:", df[column].max())

    print("Minimum:", df[column].min())


# NLP Insights
print("\nImportant Dataset Keywords:")

print(word_frequency)

# ==========================================
# STEP 14: SAVE CLEANED DATASET
# ==========================================

output_file = "cleaned_dataset.csv"

df.to_csv(output_file, index=False)

print("\nCleaned Dataset Saved Successfully!")

print("File:", output_file)

# ==========================================
# STEP 15: GENERATE REPORT
# ==========================================

report = f"""

============================================
        AI DATA ANALYST REPORT
============================================

Dataset Name:
{os.path.basename(file_path)}

Total Rows:
{df.shape[0]}

Total Columns:
{df.shape[1]}

Duplicate Records Removed:
{duplicate_count}

Missing Values Found:
{missing_values.sum()}

============================================
COLUMN INFORMATION
============================================

{df.dtypes}

============================================
STATISTICAL ANALYSIS
============================================

{df.describe()}

============================================
OUTLIER ANALYSIS
============================================

{outlier_report}

============================================
NLP KEYWORDS
============================================

{word_frequency}

============================================
DATA CLEANING COMPLETED
============================================

"""


with open("analysis_report.txt", "w") as file:

    file.write(report)


print("\nAnalysis Report Generated Successfully!")

print("File: analysis_report.txt")

print("\nAI DATA ANALYSIS COMPLETED!")